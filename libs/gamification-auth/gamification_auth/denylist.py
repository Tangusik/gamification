"""Формат ключа denylist отозванных токенов.

Ключ общий контракт между users (пишет отзыв при выходе) и остальными
сервисами (читают отзыв только для чтения, fail-open). Формат обязан
оставаться единым — разъехавшись, denylist работал бы только частично,
пока это не было бы замечено.

Значение — ``users:denylist:jti:<jti>``, то же, что и раньше жило
непосредственно в ``services/users/app/repositories/denylist.py``.
Перенесено сюда, потому что это часть формата токена (``jti``), а не
деталь одного сервиса.
"""

KEY_PREFIX = "users:denylist:jti:"


def denylist_key(jti: str) -> str:
    """Собрать ключ Redis для идентификатора токена (``jti``)."""
    return f"{KEY_PREFIX}{jti}"
