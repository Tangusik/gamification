"""Ошибки проверки токена.

HTTP библиотека не знает: перевод в коды ответов — задача сервиса.
Разделение на три типа не косметическое, оно повторяет разницу в том,
что клиенту делать дальше:

* ``TokenExpiredError`` — обновить пару токенов и повторить запрос;
* ``TokenClaimsError`` — токен выпущен не по нашему формату, идти на
  логин; повтор не поможет;
* ``TokenInvalidError`` — подпись, аудитория или алгоритм не сошлись;
  идти на логин.

Тексты ошибок не содержат ни самого токена, ни его нагрузки: они
попадают в логи.
"""


class TokenError(Exception):
    """Базовая ошибка проверки токена."""


class TokenInvalidError(TokenError):
    """Подпись, аудитория, алгоритм или формат токена не сошлись."""


class TokenExpiredError(TokenError):
    """Срок действия токена истёк."""


class TokenClaimsError(TokenError):
    """В токене нет обязательного claim."""
