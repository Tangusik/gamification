"""Прикладные claims, попадающие в JWT доступа."""

from typing import Any

from app.business.domain.entities import InstitutionContext


def build_token_claims(
    user: object, context: InstitutionContext | None
) -> dict[str, Any]:
    """Собрать прикладные claims для токена доступа.

    Токен выпускается в контексте **одного** выбранного учреждения,
    поэтому активный контекст приходит отдельным аргументом, а не
    берётся из пользователя: users не хранит членств вовсе, источник
    истины о них — gamification. При обычном логине контекста нет,
    при внутреннем выпуске (``POST /internal/tokens/institution-context``)
    его приносит gamification, приняв на веру пару «учреждение + роль».
    Функция остаётся чистой и в хранилище не ходит: она тестируется без
    HTTP и переиспользуется вне него.

    ``context is None`` — законное состояние, а не ошибка: так выглядит
    токен сразу после логина и токен владельца инсталляции. В этом
    случае в результате **нет ключей** ``role`` и ``institution_id``
    вовсе — именно отсутствие, а не ``null``. По нему соседние сервисы
    отличают владельца инсталляции от актора учреждения, не выдумывая
    отдельного значения роли.

    Аргумент ``user`` сейчас не используется, но остаётся в сигнатуре:
    следующие claims будут именно от пользователя, а второй раз ломать
    подпись дороже, чем держать неиспользуемый параметр. Тип —
    ``object``, а не ``AppUserProtocol``: этот модуль лежит в слое
    ``business``, которому запрещено импортировать каркасы, а
    ``AppUserProtocol`` зависит от fastapi-users. Поскольку параметр не
    используется, более узкий тип ничего не проверял бы на практике.

    Claims нужны **другим микросервисам и фронтенду**: имея роль и
    учреждение прямо в токене, они принимают решение о показе раздела
    или о допуске к своему ресурсу, не обращаясь в ``users`` на каждый
    запрос. Роль и учреждение здесь принимаются на веру — их проверка
    («состоит ли пользователь в учреждении именно с этой ролью») лежит
    на gamification, а не на users: у users больше нет хранилища, по
    которому это можно бы было перепроверить.

    В claims не кладётся ничего чувствительного: ни email, ни хеш
    пароля, ни флаги учётной записи. Токен читаем любым получателем.

    ``sub``, ``aud`` и ``jti`` здесь намеренно не формируются: их задаёт
    стратегия, и claims не имеют права их переопределить.
    """
    if context is None:
        return {}
    return {
        "role": context.role,
        "institution_id": str(context.institution_id),
    }
