/// Идентификатор идемпотентной операции (`operation_id`).
///
/// Зеркало `services/web/src/utils/uuid.ts`: там UUID собирается вручную,
/// потому что `crypto.randomUUID()` недоступен вне secure context. У Flutter
/// этого ограничения нет, поэтому здесь просто `package:uuid`.
library;

import 'package:uuid/uuid.dart';

const Uuid _uuid = Uuid();

/// Сгенерировать новый `operation_id`.
///
/// **Политику смены применяет экран (Ч5), не этот модуль** — буквально как
/// описано в `.claude/knowledge/web-service/01-structure.md` (раздел
/// «Маркет привилегий»): id создаётся один раз при открытии формы или
/// попытке покупки и **не меняется** при сетевой ошибке, таймауте или любом
/// отказе, кроме `PRICE_CHANGED` — повтор с тем же id остаётся идемпотентным,
/// сервер либо вернёт уже созданную запись, либо снова тот же отказ. Новый id
/// нужен **только** после успеха или после `PRICE_CHANGED`: цена в форме уже
/// другая, и повтор со старым id и другим `expected_price` дал бы
/// `OPERATION_ID_CONFLICT` вместо ожидаемого исхода.
String newOperationId() => _uuid.v4();
