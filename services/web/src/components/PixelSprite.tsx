/**
 * Пиксельный спрайт 8×8 из дизайн-документа («1c Контрастный», Nocturne).
 *
 * Карты пикселей и золотая палитра монеты взяты из
 * `.claude/plans/Gamification Design.html` (раздел brand-tokens, компонент
 * спрайтов). Рисуется SVG-элементами `<rect>` — без внешних файлов и без
 * `dangerouslySetInnerHTML`, поэтому не задевает CSP без `'unsafe-inline'`.
 *
 * Спрайт декоративный (`aria-hidden`): рядом всегда есть текстовая подпись,
 * саму иконку для скринридера не озвучиваем.
 */

export type SpriteName =
  | 'coin'
  | 'star'
  | 'heart'
  | 'bolt'
  | 'trophy'
  | 'chest'
  | 'check'
  | 'qr'
  | 'house'
  | 'user'
  | 'cam'

/** Карта 8×8: `.` — пусто, остальные символы — закрашенный пиксель. */
const MAPS: Record<SpriteName, readonly string[]> = {
  coin: ['..####..', '.#GGGG#.', '#GGLLGG#', '#GLGGLG#', '#GLGGLG#', '#GGLLGG#', '.#GGGG#.', '..####..'],
  star: ['...##...', '...##...', '.######.', '..####..', '..####..', '.##..##.', '##....##', '........'],
  heart: ['.##..##.', '########', '########', '########', '.######.', '..####..', '...##...', '........'],
  bolt: ['....##..', '...###..', '..###...', '.#####..', '..####..', '...##...', '..##....', '.#......'],
  trophy: ['########', '#.####.#', '#.####.#', '.######.', '..####..', '...##...', '..####..', '.######.'],
  chest: ['.######.', '#......#', '########', '##.##.##', '#..##..#', '#......#', '########', '........'],
  check: ['........', '......##', '.....##.', '....##..', '##.##...', '###.....', '.#......', '........'],
  qr: ['###.#.##', '#.#.#.#.', '###..###', '...#....', '#.##.#.#', '###..###', '#.#.#..#', '###.####'],
  house: ['...##...', '..####..', '.######.', '########', '.#....#.', '.#.##.#.', '.#.##.#.', '.######.'],
  user: ['..####..', '.######.', '.######.', '..####..', '........', '.######.', '########', '########'],
  cam: ['..#..#..', '########', '#......#', '#..##..#', '#.#..#.#', '#..##..#', '#......#', '########'],
}

/** Золотая палитра монеты из дизайна — используется по умолчанию, пока цвет не переопределён пропом. */
const COIN_TONES: Record<string, string> = { '#': '#7a5a00', G: '#ffc31a', L: '#fff0a8' }

type Props = {
  name: SpriteName
  /** Сторона квадрата в px. По умолчанию 16 — как в дизайне для меню и подписей. */
  size?: number
  /** Цвет заливки. По умолчанию — `currentColor`, кроме монеты: она без переопределения рисуется золотой палитрой дизайна. */
  color?: string
}

export function PixelSprite({ name, size = 16, color = 'currentColor' }: Props) {
  const rows = MAPS[name]
  const useCoinTones = name === 'coin' && color === 'currentColor'

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 8 8"
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
      style={{ display: 'inline-block', verticalAlign: 'middle', flex: 'none' }}
    >
      {rows.flatMap((row, y) =>
        [...row].map((ch, x) => {
          if (ch === '.') return null
          const fill = useCoinTones ? (COIN_TONES[ch] ?? color) : color
          return <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={fill} />
        }),
      )}
    </svg>
  )
}
